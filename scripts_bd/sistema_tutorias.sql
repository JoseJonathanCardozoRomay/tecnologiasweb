CREATE DATABASE IF NOT EXISTS tutorias_db
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;
USE tutorias_db;

SET FOREIGN_KEY_CHECKS = 0;
DROP VIEW IF EXISTS vista_tutorias_personales;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE IF NOT EXISTS roles (
  id_rol INT AUTO_INCREMENT PRIMARY KEY,
  nombre_rol VARCHAR(30) NOT NULL UNIQUE,
  descripcion VARCHAR(150) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS usuarios (
  id_usuario INT AUTO_INCREMENT PRIMARY KEY,
  id_rol INT NOT NULL,
  nombre VARCHAR(100) NOT NULL,
  apellido VARCHAR(100) NOT NULL,
  correo VARCHAR(150) NOT NULL UNIQUE,
  usuario VARCHAR(50) NOT NULL UNIQUE,
  contrasena_hash VARCHAR(255) NOT NULL,
  telefono VARCHAR(20) NULL,
  estado ENUM('activo','inactivo') NOT NULL DEFAULT 'activo',
  fecha_registro DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_usuarios_roles FOREIGN KEY (id_rol) REFERENCES roles(id_rol) ON UPDATE CASCADE,
  INDEX idx_usuarios_rol_estado (id_rol, estado),
  INDEX idx_usuarios_apellido (apellido, nombre)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS registro_intentos (
  id_intento INT AUTO_INCREMENT PRIMARY KEY,
  usuario_ingresado VARCHAR(100) NULL,
  id_usuario INT NULL,
  ip_origen VARCHAR(45) NULL,
  resultado ENUM('exitoso','fallido') NOT NULL,
  motivo VARCHAR(255) NULL,
  fecha_hora DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_intentos_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
  INDEX idx_intentos_fecha (fecha_hora),
  INDEX idx_intentos_usuario (id_usuario)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS carreras (
  id_carrera INT AUTO_INCREMENT PRIMARY KEY,
  nombre_carrera VARCHAR(150) NOT NULL UNIQUE,
  estado ENUM('activo','inactivo') NOT NULL DEFAULT 'activo',
  INDEX idx_carreras_estado (estado)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS estudiantes (
  id_estudiante INT AUTO_INCREMENT PRIMARY KEY,
  id_usuario INT NOT NULL UNIQUE,
  id_carrera INT NOT NULL,
  semestre TINYINT UNSIGNED NOT NULL,
  registro_universitario VARCHAR(30) UNIQUE,
  CONSTRAINT chk_estudiante_semestre CHECK (semestre BETWEEN 1 AND 12),
  CONSTRAINT fk_estudiantes_usuarios FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_estudiantes_carreras FOREIGN KEY (id_carrera) REFERENCES carreras(id_carrera) ON UPDATE CASCADE,
  INDEX idx_estudiante_carrera_semestre (id_carrera, semestre)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tutores (
  id_tutor INT AUTO_INCREMENT PRIMARY KEY,
  id_usuario INT NOT NULL UNIQUE,
  especialidad VARCHAR(150) NULL,
  biografia TEXT NULL,
  foto_perfil VARCHAR(255) NULL,
  perfil_linkedin VARCHAR(255) NULL,
  certificaciones TEXT NULL,
  areas_expertise TEXT NULL,
  CONSTRAINT fk_tutores_usuarios FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS materias (
  id_materia INT AUTO_INCREMENT PRIMARY KEY,
  nombre_materia VARCHAR(150) NOT NULL,
  id_carrera INT NOT NULL,
  estado ENUM('activo','inactivo') NOT NULL DEFAULT 'activo',
  CONSTRAINT uq_materia_carrera UNIQUE (id_carrera, nombre_materia),
  CONSTRAINT fk_materias_carreras FOREIGN KEY (id_carrera) REFERENCES carreras(id_carrera) ON UPDATE CASCADE,
  INDEX idx_materias_estado (estado),
  INDEX idx_materias_carrera (id_carrera)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tutor_materia (
  id_tutor INT NOT NULL,
  id_materia INT NOT NULL,
  PRIMARY KEY (id_tutor, id_materia),
  CONSTRAINT fk_tm_tutor FOREIGN KEY (id_tutor) REFERENCES tutores(id_tutor) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_tm_materia FOREIGN KEY (id_materia) REFERENCES materias(id_materia) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS disponibilidad_tutor (
  id_disponibilidad INT AUTO_INCREMENT PRIMARY KEY,
  id_tutor INT NOT NULL,
  dia_semana ENUM('Lunes','Martes','Miercoles','Jueves','Viernes','Sabado') NOT NULL,
  hora_inicio TIME NOT NULL,
  hora_fin TIME NOT NULL,
  CONSTRAINT chk_disponibilidad_horas CHECK (hora_inicio < hora_fin),
  CONSTRAINT fk_disp_tutor FOREIGN KEY (id_tutor) REFERENCES tutores(id_tutor) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT uq_disponibilidad_exacta UNIQUE (id_tutor, dia_semana, hora_inicio, hora_fin),
  INDEX idx_disp_tutor_dia (id_tutor, dia_semana)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS periodos_tutoria (
  id_periodo INT AUTO_INCREMENT PRIMARY KEY,
  codigo VARCHAR(20) NOT NULL UNIQUE,
  nombre VARCHAR(100) NOT NULL,
  fecha_inicio DATE NOT NULL,
  fecha_fin DATE NOT NULL,
  activo TINYINT(1) NOT NULL DEFAULT 1,
  creado_por INT NULL,
  fecha_creacion DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_periodo_fechas CHECK (fecha_fin >= fecha_inicio),
  CONSTRAINT fk_periodo_creado_por FOREIGN KEY (creado_por) REFERENCES usuarios(id_usuario) ON DELETE SET NULL ON UPDATE CASCADE,
  INDEX idx_periodo_activo (activo),
  INDEX idx_periodo_fechas (fecha_inicio, fecha_fin)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS bloques_horarios (
  id_bloque INT AUTO_INCREMENT PRIMARY KEY,
  nombre_bloque VARCHAR(30) NOT NULL UNIQUE,
  hora_inicio TIME NOT NULL,
  hora_fin TIME NOT NULL,
  descripcion VARCHAR(200) NULL,
  estado ENUM('activo','inactivo') NOT NULL DEFAULT 'activo',
  CONSTRAINT chk_bloque_horas CHECK (hora_inicio < hora_fin)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS proyectos_grado (
  id_proyecto INT AUTO_INCREMENT PRIMARY KEY,
  id_estudiante INT NOT NULL,
  id_carrera INT NOT NULL,
  titulo VARCHAR(250) NOT NULL,
  descripcion TEXT NULL,
  estado ENUM('propuesto','en_proceso','finalizado','cancelado') NOT NULL DEFAULT 'propuesto',
  fecha_registro DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_proyectos_estudiante FOREIGN KEY (id_estudiante) REFERENCES estudiantes(id_estudiante) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_proyectos_carrera FOREIGN KEY (id_carrera) REFERENCES carreras(id_carrera) ON UPDATE CASCADE,
  CONSTRAINT uq_proyecto_titulo_carrera UNIQUE (id_carrera, titulo),
  INDEX idx_proyecto_estudiante_estado (id_estudiante, estado)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =========================================================
-- TUTORÍAS PERSONALES / FIN DE CARRERA
-- =========================================================
CREATE TABLE IF NOT EXISTS tutorias (
  id_tutoria INT AUTO_INCREMENT PRIMARY KEY,
  id_estudiante INT NOT NULL,
  id_tutor INT NOT NULL,
  id_materia INT NULL,
  id_proyecto INT NULL,
  id_bloque INT NULL,
  periodo VARCHAR(30) NULL,
  fecha DATE NOT NULL,
  hora_inicio TIME NOT NULL,
  hora_fin TIME NOT NULL,
  modalidad ENUM('presencial','virtual') NOT NULL DEFAULT 'presencial',
  lugar_o_enlace VARCHAR(200) NULL,
  estado ENUM('pendiente','programada','rechazada','realizada','cancelada','en_proceso','detenido') NOT NULL DEFAULT 'pendiente',
  estado_tutor ENUM('pendiente','aceptada','rechazada') NOT NULL DEFAULT 'pendiente',
  confirmada_admin TINYINT(1) NOT NULL DEFAULT 0,
  confirmada_por_usuario INT NULL,
  fecha_aceptacion_tutor DATETIME NULL,
  fecha_confirmacion_admin DATETIME NULL,
  observaciones TEXT NULL,
  motivo_cancelacion VARCHAR(500) NULL,
  cancelado_por_usuario INT NULL,
  fecha_cancelacion DATETIME NULL,
  fecha_solicitud DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_tutoria_horas CHECK (hora_inicio < hora_fin),
  CONSTRAINT fk_tutorias_estudiante FOREIGN KEY (id_estudiante) REFERENCES estudiantes(id_estudiante) ON UPDATE CASCADE,
  CONSTRAINT fk_tutorias_tutor FOREIGN KEY (id_tutor) REFERENCES tutores(id_tutor) ON UPDATE CASCADE,
  CONSTRAINT fk_tutorias_materia FOREIGN KEY (id_materia) REFERENCES materias(id_materia) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_tutorias_proyecto FOREIGN KEY (id_proyecto) REFERENCES proyectos_grado(id_proyecto) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_tutorias_bloque FOREIGN KEY (id_bloque) REFERENCES bloques_horarios(id_bloque) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_tutorias_confirmada_por FOREIGN KEY (confirmada_por_usuario) REFERENCES usuarios(id_usuario) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_tutorias_cancelado_por FOREIGN KEY (cancelado_por_usuario) REFERENCES usuarios(id_usuario) ON DELETE SET NULL ON UPDATE CASCADE,
  INDEX idx_tutoria_tutor_fecha (id_tutor, fecha, hora_inicio),
  INDEX idx_tutoria_estudiante_fecha (id_estudiante, fecha, hora_inicio),
  INDEX idx_tutoria_estado_fecha (estado, fecha),
  INDEX idx_tutoria_aprobacion (estado_tutor, confirmada_admin),
  INDEX idx_tutoria_proyecto (id_proyecto),
  INDEX idx_tutoria_periodo (periodo),
  INDEX idx_tutoria_cancelacion (fecha_cancelacion, cancelado_por_usuario)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS evaluaciones_tutoria (
  id_evaluacion INT AUTO_INCREMENT PRIMARY KEY,
  id_tutoria INT NOT NULL UNIQUE,
  calificacion TINYINT UNSIGNED NOT NULL,
  comentario TEXT NULL,
  fecha_evaluacion DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_evaluacion_calificacion CHECK (calificacion BETWEEN 1 AND 5),
  CONSTRAINT fk_evaluaciones_tutoria FOREIGN KEY (id_tutoria) REFERENCES tutorias(id_tutoria) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS seguimiento_sesion (
  id_seguimiento INT AUTO_INCREMENT PRIMARY KEY,
  id_tutoria INT NOT NULL UNIQUE,
  asistio ENUM('si','no') NOT NULL,
  temas_tratados TEXT NULL,
  avance ENUM('sin_avance','parcial','logrado') NULL,
  recomendaciones TEXT NULL,
  fecha_registro DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_seguimiento_tutoria FOREIGN KEY (id_tutoria) REFERENCES tutorias(id_tutoria) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =========================================================
-- TUTORÍAS GRUPALES DE MATERIAS
-- =========================================================
-- Estos horarios son institucionales: el estudiante no los define.
CREATE TABLE IF NOT EXISTS horarios_tutoria_grupal (
  id_horario INT AUTO_INCREMENT PRIMARY KEY,
  id_materia INT NOT NULL,
  id_tutor INT NOT NULL,
  dia_semana ENUM('Lunes','Martes','Miercoles','Jueves','Viernes') NOT NULL,
  turno ENUM('manana','tarde','noche') NOT NULL,
  hora_inicio TIME NOT NULL,
  hora_fin TIME NOT NULL,
  estado ENUM('activo','inactivo') NOT NULL DEFAULT 'activo',
  CONSTRAINT chk_horario_grupal_horas CHECK (hora_inicio < hora_fin),
  CONSTRAINT fk_horario_grupal_materia FOREIGN KEY (id_materia) REFERENCES materias(id_materia) ON UPDATE CASCADE,
  CONSTRAINT fk_horario_grupal_tutor FOREIGN KEY (id_tutor) REFERENCES tutores(id_tutor) ON UPDATE CASCADE,
  CONSTRAINT uq_horario_tutor_bloque UNIQUE (id_tutor, dia_semana, turno),
  INDEX idx_horario_grupal_materia (id_materia),
  INDEX idx_horario_grupal_tutor (id_tutor),
  INDEX idx_horario_grupal_estado (estado)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tutorias_grupales (
  id_tutoria_grupal INT AUTO_INCREMENT PRIMARY KEY,
  id_horario INT NOT NULL,
  fecha DATE NOT NULL,
  estado ENUM('programada','en_curso','realizada','cancelada') NOT NULL DEFAULT 'programada',
  observaciones TEXT NULL,
  motivo_cancelacion VARCHAR(500) NULL,
  cancelado_por_usuario INT NULL,
  fecha_cancelacion DATETIME NULL,
  fecha_creacion DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_tg_horario FOREIGN KEY (id_horario) REFERENCES horarios_tutoria_grupal(id_horario) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_tg_cancelado_por FOREIGN KEY (cancelado_por_usuario) REFERENCES usuarios(id_usuario) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT uq_tg_horario_fecha UNIQUE (id_horario, fecha),
  INDEX idx_tg_fecha_estado (fecha, estado),
  INDEX idx_tg_cancelacion (fecha_cancelacion, cancelado_por_usuario)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tutoria_grupal_estudiante (
  id_tutoria_grupal INT NOT NULL,
  id_estudiante INT NOT NULL,
  estado ENUM('pendiente','aprobada','inscrito','retirado','asistio','no_asistio') NOT NULL DEFAULT 'pendiente',
  fecha_inscripcion DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_actualizacion DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id_tutoria_grupal, id_estudiante),
  CONSTRAINT fk_tge_tutoria FOREIGN KEY (id_tutoria_grupal) REFERENCES tutorias_grupales(id_tutoria_grupal) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_tge_estudiante FOREIGN KEY (id_estudiante) REFERENCES estudiantes(id_estudiante) ON DELETE CASCADE ON UPDATE CASCADE,
  INDEX idx_tge_estudiante_estado (id_estudiante, estado)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS notificaciones (
  id_notificacion INT AUTO_INCREMENT PRIMARY KEY,
  id_usuario INT NOT NULL,
  tipo VARCHAR(30) NOT NULL,
  mensaje VARCHAR(255) NOT NULL,
  url VARCHAR(200) NULL,
  leida TINYINT(1) NOT NULL DEFAULT 0,
  fecha_creacion DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_notif_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario) ON DELETE CASCADE ON UPDATE CASCADE,
  INDEX idx_notif_usuario_leida (id_usuario, leida, fecha_creacion)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS registro_accesos (
  id_acceso INT AUTO_INCREMENT PRIMARY KEY,
  id_usuario INT NULL,
  fecha_hora DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ip_origen VARCHAR(45) NULL,
  resultado ENUM('exitoso','fallido') NOT NULL,
  accion VARCHAR(40) NULL,
  modulo VARCHAR(80) NULL,
  descripcion VARCHAR(500) NULL,
  CONSTRAINT fk_accesos_usuarios FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario) ON DELETE SET NULL ON UPDATE CASCADE,
  INDEX idx_auditoria_fecha (fecha_hora),
  INDEX idx_auditoria_usuario (id_usuario),
  INDEX idx_auditoria_modulo (modulo, accion)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

