CREATE OR REPLACE VIEW vista_tutorias_personales AS
SELECT t.id_tutoria,t.id_estudiante,t.id_tutor,t.id_materia,t.id_proyecto,t.periodo,
       t.fecha,t.hora_inicio,t.hora_fin,t.modalidad,t.lugar_o_enlace,t.estado,
       t.estado_tutor,t.confirmada_admin,t.confirmada_por_usuario,
       t.fecha_aceptacion_tutor,t.fecha_confirmacion_admin,
       t.observaciones,t.motivo_cancelacion,t.cancelado_por_usuario,t.fecha_cancelacion,
       CONCAT(ue.nombre,' ',ue.apellido) AS estudiante,
       CONCAT(ut.nombre,' ',ut.apellido) AS tutor,
       pg.titulo AS proyecto_grado,
       c.nombre_carrera,
       m.nombre_materia
FROM tutorias t
INNER JOIN estudiantes e ON e.id_estudiante=t.id_estudiante
INNER JOIN usuarios ue ON ue.id_usuario=e.id_usuario
INNER JOIN tutores tr ON tr.id_tutor=t.id_tutor
INNER JOIN usuarios ut ON ut.id_usuario=tr.id_usuario
LEFT JOIN proyectos_grado pg ON pg.id_proyecto=t.id_proyecto
LEFT JOIN carreras c ON c.id_carrera=e.id_carrera
LEFT JOIN materias m ON m.id_materia=t.id_materia;
